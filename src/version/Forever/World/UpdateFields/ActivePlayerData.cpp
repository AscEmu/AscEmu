    Fields::ActivePlayerData makeConservativeActivePlayerData(Fields::ActivePlayerData const& source)
    {
        // Forever live profile:
        // Keep only fields whose placement/encoding has been established from
        // verified Forever wire data. Everything else intentionally stays at the protocol's
        // minimal zero/empty state until their semantics are verified.
        //
        // Unproven modern regions are represented only by zeroed
        // opaque Forever wire spans.
        Fields::ActivePlayerData result{};

        // Proven prefix. Packed GUID length is part of the wire layout, so keep
        // the real inventory/observer GUID state instead of fixed packet bytes.
        result.invSlots = source.invSlots;
        result.farsightObject = source.farsightObject;
        result.summonedBattlePetGuid = source.summonedBattlePetGuid;
        result.knownTitles = source.knownTitles;
        result.coinage = source.coinage;
        result.accountBankCoinage = source.accountBankCoinage;
        result.xp = source.xp;
        result.nextLevelXp = source.nextLevelXp;

        // SkillInfo layout is now wire/runtime verified as the 4200-byte
        // block immediately following the core scalars.
        result.skill = source.skill;

        // The complete 104-byte post-SkillInfo 26x32-bit cluster is structurally identified.
        // Storage identifiers are neutral wire-position names. Definitions::ActivePlayerDataCreateFields
        // retains the former modern labels only as REFERENCE metadata. Copying live source values
        // here therefore cannot accidentally promote those labels to verified Forever semantics.
        result.unknownI32AfterSkill0 = source.unknownI32AfterSkill0;
        result.unknownI32AfterSkill1 = source.unknownI32AfterSkill1;
        result.unknownU32AfterSkill2 = source.unknownU32AfterSkill2;
        result.unknownFloatAfterSkill3 = source.unknownFloatAfterSkill3;
        result.unknownFloatAfterSkill4 = source.unknownFloatAfterSkill4;
        result.unknownFloatAfterSkill5 = source.unknownFloatAfterSkill5;
        result.unknownFloatAfterSkill6 = source.unknownFloatAfterSkill6;
        result.blockPercentage = source.blockPercentage;
        result.dodgePercentage = source.dodgePercentage;
        result.unknownFloatAfterSkill9 = source.unknownFloatAfterSkill9;
        result.parryPercentage = source.parryPercentage;
        result.unknownFloatAfterSkill11 = source.unknownFloatAfterSkill11;
        result.critPercentage = source.critPercentage;
        result.rangedCritPercentage = source.rangedCritPercentage;
        result.offhandCritPercentage = source.offhandCritPercentage;
        result.unknownFloatAfterSkill15 = source.unknownFloatAfterSkill15;
        result.shieldBlock = source.shieldBlock;
        result.shieldBlockCritPercentage = source.shieldBlockCritPercentage;
        result.unknownFloatAfterSkill18 = source.unknownFloatAfterSkill18;
        result.unknownFloatAfterSkill19 = source.unknownFloatAfterSkill19;
        result.unknownFloatAfterSkill20 = source.unknownFloatAfterSkill20;
        result.unknownFloatAfterSkill21 = source.unknownFloatAfterSkill21;
        result.unknownI32AfterSkill22 = source.unknownI32AfterSkill22;
        result.unknownFloatAfterSkill23 = source.unknownFloatAfterSkill23;
        result.unknownFloatAfterSkill24 = source.unknownFloatAfterSkill24;
        result.unknownFloatAfterSkill25 = source.unknownFloatAfterSkill25;

        // Forever create defaults for the still-unresolved
        // post-SkillInfo spans. These bytes now flow through our field
        // model and writer instead of being spliced directly from the
        // legacy packet template. Replace individual values with live semantics
        // as their live semantics are identified.
        std::copy_n(PostSkillDefaults.begin(), Fields::ActivePlayerData::PostSkillHeaderSize, result.unknownPostSkillHeader.begin());
        std::size_t postSkillSeedOffset = Fields::ActivePlayerData::PostSkillHeaderSize;
        for (Fields::ActivePlayerData::PostSkillRecord& record : result.unknownPostSkillRecords)
        {
            std::memcpy(&record.unknown0, PostSkillDefaults.data() + postSkillSeedOffset + 0, sizeof(record.unknown0));
            std::memcpy(&record.unknown4, PostSkillDefaults.data() + postSkillSeedOffset + 4, sizeof(record.unknown4));
            std::memcpy(&record.multiplier0, PostSkillDefaults.data() + postSkillSeedOffset + 8, sizeof(record.multiplier0));
            std::memcpy(&record.multiplier1, PostSkillDefaults.data() + postSkillSeedOffset + 12, sizeof(record.multiplier1));
            postSkillSeedOffset += 16;
        }
        std::copy_n(PostSkillDefaults.begin() + postSkillSeedOffset, Fields::ActivePlayerData::PostSkillTailSize, result.unknownPostSkillTail.begin());

        std::copy_n(PreOutfitDefaults.begin(), Fields::ActivePlayerData::UnknownBeforeOutfitSize, result.unknownBeforeOutfit.begin());

        // The following 32-bit slot exists on the wire immediately after
        // NextLevelXP, but its Forever semantics are not proven. Keep
        // unknownAfterNextLevelXp at its zero default until differential testing
        // demonstrates what it represents.

        // Shared Forever default outfit state. These records are now
        // represented as typed protocol defaults rather than retained packet bytes.
        result.unknownOutfitScalar0 = 2u;
        result.unknownOutfitScalar1 = 3u;
        applyDefaultTransmogOutfit(result.viewedOutfit, 3u, 1u, "Outfit 2", true, 1u);
        result.additionalOutfits.resize(2);
        applyDefaultTransmogOutfit(result.additionalOutfits[0], 2u, 1u, "Outfit 1", true, 1u);
        applyDefaultTransmogOutfit(result.additionalOutfits[1], 1u, 0u, "Outfit", false, 0u);
        result.transmogMetadata.situationTrigger = 0u;
        result.transmogMetadata.transmogOutfitId = 2u;
        result.transmogMetadata.stampedOptionMainHand = 0u;
        result.transmogMetadata.stampedOptionOffHand = 0u;
        result.transmogMetadata.costMod = 1.0f;
        result.transmogMetadata.locked = false;

        return result;
    }

    bool writeActivePlayerDataCreate(ByteBuffer& data, Fields::ActivePlayerData const& fields)
    {
        // Verification source of truth: Definitions::ActivePlayerDataCreateFields. In particular,
        // the post-SkillInfo storage names are neutral; former semantic labels remain REFERENCE-only metadata.
        if (!hasRequiredActivePlayerOpaqueRecords(fields))
            return false;

        for (WoWGuid const& value : fields.invSlots)
            writeModernGuid(data, value);

        writeModernGuid(data, fields.farsightObject);
        writeModernGuid(data, fields.summonedBattlePetGuid);

        data << uint32_t(fields.knownTitles.size());
        data.append(fields.unknownInventoryExtension.data(), fields.unknownInventoryExtension.size());
        data << fields.coinage << fields.accountBankCoinage << fields.xp << fields.nextLevelXp << fields.unknownAfterNextLevelXp;

        writeSkillInfoCreate(data, fields.skill);

        data << fields.unknownI32AfterSkill0
             << fields.unknownI32AfterSkill1
             << fields.unknownU32AfterSkill2
             << fields.unknownFloatAfterSkill3
             << fields.unknownFloatAfterSkill4
             << fields.unknownFloatAfterSkill5
             << fields.unknownFloatAfterSkill6
             << fields.blockPercentage
             << fields.dodgePercentage
             << fields.unknownFloatAfterSkill9
             << fields.parryPercentage
             << fields.unknownFloatAfterSkill11
             << fields.critPercentage
             << fields.rangedCritPercentage
             << fields.offhandCritPercentage
             << fields.unknownFloatAfterSkill15
             << fields.shieldBlock
             << fields.shieldBlockCritPercentage
             << fields.unknownFloatAfterSkill18
             << fields.unknownFloatAfterSkill19
             << fields.unknownFloatAfterSkill20
             << fields.unknownFloatAfterSkill21
             << fields.unknownI32AfterSkill22
             << fields.unknownFloatAfterSkill23
             << fields.unknownFloatAfterSkill24
             << fields.unknownFloatAfterSkill25;

        data.append(fields.unknownPostSkillHeader.data(), fields.unknownPostSkillHeader.size());
        for (Fields::ActivePlayerData::PostSkillRecord const& record : fields.unknownPostSkillRecords)
            data << record.unknown0 << record.unknown4 << record.multiplier0 << record.multiplier1;
        data.append(fields.unknownPostSkillTail.data(), fields.unknownPostSkillTail.size());

        data.append(fields.unknownBeforeOutfit.data(), fields.unknownBeforeOutfit.size());
        data << fields.unknownOutfitScalar0 << fields.unknownOutfitScalar1;
        writeTransmogOutfitDataCreate(data, fields.viewedOutfit);
        data << uint32_t(fields.additionalOutfits.size());
        for (Fields::TransmogOutfitData const& outfit : fields.additionalOutfits)
            writeTransmogOutfitDataCreate(data, outfit);
        writeTransmogOutfitMetadataCreate(data, fields.transmogMetadata);
        data.flushBits();

        for (uint64_t value : fields.knownTitles)
            data << value;

        data.append(fields.unknownAfterTransmog.data(), fields.unknownAfterTransmog.size());
        return true;
    }

