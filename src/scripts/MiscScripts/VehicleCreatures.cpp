// Self-acting vehicles
// The core keeps a creature with a vehicle id passive until a player drives it. The templates below carry the
// vehicle id for a client mechanic only (mounting, carrying, grabbing) and fight like any other creature.
// Creatures with a script of their own are not listed, that script decides.
// sorted by entry
class SelfActingVehicle : public CreatureAIScript
{
public:
    explicit SelfActingVehicle(Creature* pCreature) : CreatureAIScript(pCreature) {}
    static CreatureAIScript* Create(Creature* c) { return new SelfActingVehicle(c); }

    void OnLoad() override
    {
        getCreature()->setAItoUse(true);
        setCanEnterCombat(true);
    }
};

