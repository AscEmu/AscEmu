    HuffmanTree::HuffmanTree()
    {
        treeInit();
    }

    void HuffmanTree::treeInit()
    {
        // items_ is already zero/null-initialized by its default member
        // initializers, replacing the original's explicit next/prev-clear
        // loop over a freshly-malloc'd tree.
        item3050_ = nullptr;
        item3054_ = reinterpret_cast<Item*>(&item3054_);
        item3058_ = bitNot(item3054_);
        item305C_ = nullptr;
        first_ = reinterpret_cast<Item*>(&first_);
        last_ = bitNot(first_);
        rebuildCount_ = 1;
        itemsUsed_ = 0;

        for (auto& qd : quickDecode_)
            qd.generation = 0;
    }

    void HuffmanTree::insertItem(Item* item, InsertMode mode, Item* relativeTo)
    {
        // The original took an explicit `p_item` (always &item305C_ at
        // every call site in this file) and derived p_item[1]/p_item[0]
        // from it via layout-dependent pointer arithmetic (p_item[1] landed
        // on `first_`, the member declared right after item305C in the
        // original struct). Since every call site passes the same p_item
        // and a null relativeTo, that always resolves to &first_ - hardcoded
        // directly here instead of replicating the cross-member arithmetic.
        Item* next = item->next;
        Item* prev = item->prev;

        if (next != nullptr)
        {
            if (asInt(prev) < 0)
                prev = bitNot(prev);
            else
                prev = prev + (item - next->prev);

            prev->next = next;
            next->prev = prev;
            item->next = nullptr;
            item->prev = nullptr;
        }

        if (relativeTo == nullptr)
            relativeTo = reinterpret_cast<Item*>(&first_);

        if (mode == InsertMode::SwitchItems)
        {
            item->next = relativeTo->next;
            item->prev = relativeTo->next->prev;
            relativeTo->next->prev = item;
            relativeTo->next = item;
            return;
        }

        // InsertMode::InsertItem
        item->next = relativeTo;
        item->prev = relativeTo->prev;

        std::intptr_t next2 = asInt(item305C_);
        Item* prev2 = relativeTo->prev;

        if (asInt(prev2) < 0)
        {
            // NOTE: the original decodes `prev` here (the item's own,
            // now-stale previous pointer captured above), not `prev2` -
            // preserved verbatim even though it reads like it should be
            // prev2; this whole branch is unreachable in every path
            // AscEmu's tools take (Huffman/WAV is never invoked), so it
            // has never been exercised against real data either way.
            prev2 = bitNot(prev);
            prev2->next = item;
            relativeTo->prev = item;
            return;
        }

        if (next2 < 0)
            next2 = relativeTo - relativeTo->next->prev;

        prev2 = prev2 + next2;
        prev2->next = item;
        relativeTo->prev = item;
    }

    void HuffmanTree::removeItem(Item* item)
    {
        if (item->next != nullptr)
        {
            Item* temp = item->prev;

            if (asInt(temp) <= 0)
                temp = bitNot(temp);
            else
                temp = temp + (item - item->next->prev);

            temp->next = item->next;
            item->next->prev = item->prev;
            item->next = nullptr;
            item->prev = nullptr;
        }
    }

    HuffmanTree::Item* HuffmanTree::previousItem(Item* item, std::intptr_t value)
    {
        if (asInt(item->prev) < 0)
            return bitNot(item->prev);

        if (value < 0)
            value = item - item->next->prev;

        return item->prev + value;
    }

    HuffmanTree::Item* HuffmanTree::call1500E740()
    {
        Item* item1 = item3058_;
        Item* item2;

        if (asInt(item1) <= 0 || (item2 = item1) == nullptr)
        {
            if ((item2 = &items_[itemsUsed_++]) != nullptr)
                item1 = item2;
            else
                item1 = first_;
        }
        else
        {
            item1 = item2;
        }

        Item* next = item1->next;

        if (next != nullptr)
        {
            Item* prev = item1->prev;

            if (asInt(prev) <= 0)
                prev = bitNot(prev);
            else
                prev = prev + (item1 - item1->next->prev);

            prev->next = next;
            next->prev = prev;
            item1->next = nullptr;
            item1->prev = nullptr;
        }

        // pp_item == &first_ in the original; pp_item[1] is the member
        // right after `first_`, which is `last_`.
        item1->next = reinterpret_cast<Item*>(&first_);
        item1->prev = last_;

        Item* prev = last_;

        if (asInt(prev) <= 0)
        {
            prev = bitNot(prev);
            prev->next = item1;
            prev->prev = item2;
            item2->parent = nullptr;
            item2->child = nullptr;
        }
        else
        {
            if (asInt(item305C_) < 0)
                prev = prev + (reinterpret_cast<Item*>(&first_) - first_->prev);
            else
                prev = prev + asInt(item305C_);

            prev->next = item1;
            last_ = item2;
            item2->parent = nullptr;
            item2->child = nullptr;
        }

        return item2;
    }

    void HuffmanTree::call1500E820(Item* item)
    {
        for (; item != nullptr; item = item->parent)
        {
            item->byteValue++;

            Item* item1 = item;
            Item* prev = nullptr;

            for (;;)
            {
                prev = item1->prev;

                if (asInt(prev) <= 0)
                {
                    prev = nullptr;
                    break;
                }

                if (prev->byteValue >= item->byteValue)
                    break;

                item1 = prev;
            }

            if (item1 == item)
                continue;

            Item* item2 = nullptr;

            if (item1->next != nullptr)
            {
                item2 = previousItem(item1, -1);
                item2->next = item1->next;
                item1->next->prev = item1->prev;
                item1->next = nullptr;
                item1->prev = nullptr;
            }

            item2 = item->next;
            item1->next = item2;
            item1->prev = item2->prev;
            item2->prev = item1;
            item->next = item1;

            if ((item2 = item1) != nullptr)
            {
                item2 = previousItem(item, -1);
                item2->next = item->next;
                item->next->prev = item->prev;
                item->next = nullptr;
                item->prev = nullptr;
            }

            if (prev == nullptr)
                prev = reinterpret_cast<Item*>(&first_);

            item2 = prev->next;
            item->next = item2;
            item->prev = item2->prev;
            item2->prev = item;
            prev->next = item;
            Item* item3 = item1->parent->child;
            item2 = item->parent;

            if (item2->child == item)
                item2->child = item1;

            if (item3 == item1)
                item1->parent->child = item;

            item2 = item->parent;
            item->parent = item1->parent;
            item1->parent = item2;

            rebuildCount_++;
        }
    }

    void HuffmanTree::buildTree(std::uint32_t compressionType)
    {
        while (asInt(last_) > 0)
        {
            if (last_->next != nullptr)
                removeItem(last_);

            item3058_ = reinterpret_cast<Item*>(&item3054_);
            last_->prev = item3058_;

            Item* temp = previousItem(reinterpret_cast<Item*>(&item3054_), reinterpret_cast<std::intptr_t>(&item3050_));
            temp->next = last_;
            item3054_ = last_;
        }

        itemByByte_.fill(nullptr);

        std::uint32_t maxByte = 0;
        std::size_t byteArrayBase = static_cast<std::size_t>(compressionType & 0xFF) * 258;
        std::uint32_t i = 0;

        for (; i < 0x100; ++i)
        {
            Item* item = item3058_;
            const std::uint8_t oneByte = kInitialWeights[byteArrayBase + i];

            if (oneByte == 0)
                continue;

            if (asInt(item) <= 0)
                item = &items_[itemsUsed_++];

            insertItem(item, InsertMode::SwitchItems, nullptr);

            item->parent = nullptr;
            item->child = nullptr;
            itemByByte_[i] = item;
            item->dcmpByte = i;
            item->byteValue = oneByte;

            if (oneByte >= maxByte)
            {
                maxByte = oneByte;
                continue;
            }

            bool found = false;
            Item* p3 = last_;

            if (asInt(p3) > 0)
            {
                while (p3 != nullptr && asInt(p3) > 0)
                {
                    if (p3->byteValue >= oneByte)
                    {
                        found = true;
                        break;
                    }

                    p3 = p3->prev;
                }
            }

            if (!found)
                p3 = nullptr;

            if (item->next != nullptr)
                removeItem(item);

            if (p3 == nullptr)
                p3 = reinterpret_cast<Item*>(&first_);

            item->next = p3->next;
            item->prev = p3->next->prev;
            p3->next->prev = item;
            p3->next = item;
        }

        for (; i < 0x102; ++i)
        {
            Item* item2 = item3058_;

            if (asInt(item2) <= 0)
                item2 = &items_[itemsUsed_++];

            insertItem(item2, InsertMode::InsertItem, nullptr);

            item2->dcmpByte = i;
            item2->byteValue = 1;
            item2->parent = nullptr;
            item2->child = nullptr;
            itemByByte_[i] = item2;
        }

        Item* child1 = last_;

        if (asInt(child1) > 0)
        {
            for (;;)
            {
                Item* child2 = child1->prev;

                if (asInt(child2) <= 0)
                    break;

                Item* item = item3058_;

                if (asInt(item) <= 0)
                    item = &items_[itemsUsed_++];

                insertItem(item, InsertMode::SwitchItems, nullptr);

                item->parent = nullptr;
                item->child = child1;
                item->byteValue = child1->byteValue + child2->byteValue;
                child1->parent = item;
                child2->parent = item;

                if (item->byteValue >= maxByte)
                {
                    maxByte = item->byteValue;
                }
                else
                {
                    Item* p2 = child2->prev;
                    bool found = false;

                    if (asInt(p2) > 0)
                    {
                        while (p2 != nullptr && asInt(p2) > 0)
                        {
                            if (p2->byteValue >= item->byteValue)
                            {
                                found = true;
                                break;
                            }

                            p2 = p2->prev;
                        }
                    }

                    if (!found)
                        p2 = nullptr;

                    if (item->next != nullptr)
                    {
                        Item* temp4 = previousItem(item, -1);
                        temp4->next = item->next;
                        item->next->prev = item->prev;
                        item->next = nullptr;
                        item->prev = nullptr;
                    }

                    if (p2 == nullptr)
                        p2 = reinterpret_cast<Item*>(&first_);

                    item->next = p2->next;
                    item->prev = p2->next->prev;
                    p2->next->prev = item;
                    p2->next = item;
                }

                child1 = child2;
            }
        }

        rebuildCount_ = 1;
    }

    std::size_t HuffmanTree::decompress(HuffmanInputStream& is, std::span<std::byte> output)
    {
        if (output.empty())
            return 0;

        std::uint32_t dcmpByte = 0;
        std::size_t outPos = 0;

        const std::uint32_t n8bits = is.get8Bits();
        buildTree(n8bits);
        cmp0_ = (n8bits == 0);

        for (;;)
        {
            const std::uint32_t n7bits = is.get7Bits();
            QuickDecode& qd = quickDecode_[n7bits];
            const bool hasQuick = (qd.generation >= rebuildCount_);
            Item* item1 = nullptr;

            if (hasQuick)
            {
                if (qd.bits > 7)
                {
                    is.consumeBits(7);
                    item1 = qd.item;
                }
                else
                {
                    is.consumeBits(qd.bits);
                    dcmpByte = qd.dcmpByte;
                }
            }
            else
            {
                item1 = first_->next->prev;
                if (asInt(item1) <= 0)
                    item1 = nullptr;
            }

            const bool needsWalk = hasQuick ? (qd.bits > 7) : true;

            if (needsWalk)
            {
                std::uint32_t bitCount = 0;
                Item* item2 = nullptr;

                do
                {
                    item1 = item1->child;

                    if (is.get1Bit())
                        item1 = item1->prev;

                    if (++bitCount == 7)
                        item2 = item1;
                } while (item1->child != nullptr);

                if (!hasQuick)
                {
                    if (bitCount > 7)
                    {
                        qd.generation = rebuildCount_;
                        qd.bits = bitCount;
                        qd.item = item2;
                    }
                    else
                    {
                        const std::uint32_t index = n7bits & (0xFFFFFFFFu >> (32 - bitCount));
                        const std::uint32_t add = (1u << bitCount);

                        for (std::uint32_t j = index; j <= 0x7F; j += add)
                        {
                            quickDecode_[j].generation = rebuildCount_;
                            quickDecode_[j].bits = bitCount;
                            quickDecode_[j].dcmpByte = item1->dcmpByte;
                        }
                    }
                }

                dcmpByte = item1->dcmpByte;
            }

            if (dcmpByte == 0x101)
            {
                const std::uint32_t n8 = is.get8Bits();
                Item* parentItem = (asInt(last_) <= 0) ? nullptr : last_;

                Item* leaf1 = call1500E740();
                leaf1->parent = parentItem;
                leaf1->dcmpByte = parentItem->dcmpByte;
                leaf1->byteValue = parentItem->byteValue;
                itemByByte_[leaf1->dcmpByte] = leaf1;

                Item* leaf2 = call1500E740();
                leaf2->parent = parentItem;
                leaf2->dcmpByte = n8;
                leaf2->byteValue = 0;
                itemByByte_[leaf2->dcmpByte] = leaf2;

                parentItem->child = leaf2;

                call1500E820(leaf2);

                if (!cmp0_)
                    call1500E820(itemByByte_[n8]);

                dcmpByte = n8;
            }

            if (dcmpByte == 0x100)
                break;

            output[outPos++] = static_cast<std::byte>(dcmpByte);

            if (outPos == output.size())
                break;

            if (cmp0_)
                call1500E820(itemByByte_[dcmpByte]);
        }

        return outPos;
    }
