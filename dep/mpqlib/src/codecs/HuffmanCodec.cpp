    void HuffmanInputStream::refill32()
    {
        std::uint32_t value = 0;
        const std::size_t avail = data_.size() > pos_ ? data_.size() - pos_ : 0;
        const std::size_t n = avail < 4 ? avail : 4;
        if (n > 0)
            std::memcpy(&value, data_.data() + pos_, n);
        pos_ += 4;
        bitBuf_ = value;
        bits_ = 32;
    }

    void HuffmanInputStream::refill16()
    {
        std::uint16_t value = 0;
        const std::size_t avail = data_.size() > pos_ ? data_.size() - pos_ : 0;
        const std::size_t n = avail < 2 ? avail : 2;
        if (n > 0)
            std::memcpy(&value, data_.data() + pos_, n);
        pos_ += 2;
        bitBuf_ |= (static_cast<std::uint32_t>(value) << bits_);
        bits_ += 16;
    }

    std::uint32_t HuffmanInputStream::get1Bit()
    {
        const std::uint32_t bit = bitBuf_ & 1;
        bitBuf_ >>= 1;
        if (--bits_ == 0)
            refill32();
        return bit;
    }

    std::uint32_t HuffmanInputStream::get7Bits()
    {
        if (bits_ <= 7)
            refill16();
        return bitBuf_ & 0x7F;
    }

    std::uint32_t HuffmanInputStream::get8Bits()
    {
        if (bits_ <= 8)
            refill16();

        const std::uint32_t oneByte = bitBuf_ & 0xFF;
        bitBuf_ >>= 8;
        bits_ -= 8;
        return oneByte;
    }

    void HuffmanInputStream::consumeBits(std::uint32_t count)
    {
        bitBuf_ >>= count;
        bits_ -= count;
    }

