    // Ports of the original PTR_INT/PTR_NOT macros: a tree item pointer
    // whose full pointer-width signed representation is negative is not
    // a real pointer at all, but an encoded sentinel produced by the
    // same bitwise-NOT operation (self-inverse: applying it twice
    // returns the original value). The original used `long`, which on
    // 64-bit Windows is only 32 bits (LLP64) and would truncate real
    // pointers - using the full pointer width here is what the 32-bit
    // original's own logic actually depended on (a real heap pointer's
    // sign bit is never set), not a behavior change.
    std::intptr_t HuffmanTree::asInt(const Item* p)
    {
        return static_cast<std::intptr_t>(reinterpret_cast<std::uintptr_t>(p));
    }

    HuffmanTree::Item* HuffmanTree::bitNot(const Item* p)
    {
        return reinterpret_cast<Item*>(~reinterpret_cast<std::uintptr_t>(p));
    }

